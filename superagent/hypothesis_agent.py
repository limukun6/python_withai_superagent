"""Single-agent experiment selection with mechanically checked expectations."""
from __future__ import annotations

from copy import deepcopy
from dataclasses import asdict, dataclass
import math
from typing import Any


STRATEGIES = ("reflective", "reflective_no_feedback")
METRICS = ("search_score", "score_gap", "search_accuracy", "generalization_gap", "training_seconds")
PROFILE_FIELDS = (
    "evaluation_protocol","primary_metric",
    "class_count","train_rows","feature_shape","pixel_dtype","numeric_columns","categorical_column_count","text_column_count","document_count",
    "task_kind", "train_label_counts", "validation_label_counts", "feature_count",
    "unique_values_per_column", "missing_values_per_column", "constant_columns",
    "duplicate_train_feature_rows", "input_pair_count", "empty_text_count", "word_count",
)
OBSERVATION_FIELDS = (
    "primary_metric","train_score","search_score","score_gap","trial", "status", "train_accuracy", "search_accuracy", "generalization_gap",
    "class_recall", "training_seconds", "error", "hypothesis_check",
)


@dataclass(frozen=True)
class Proposal:
    candidate: str
    reason: str
    hypothesis: str
    review: str
    evidence_trials: list[int]
    expected_change: dict[str, Any] | None

    def record(self) -> dict[str, Any]:
        return asdict(self)


def build_state(profile, history, available, limit, feedback_visible=True):
    """Only inner-search observations enter memory; held-out scores are excluded."""
    plans = []
    for row in history:
        plan = {key: deepcopy(row[key]) for key in ("trial", "candidate", "params") if key in row}
        # Previous proposals were made before their experiment's outcome. In the
        # blind arm they are generated by that blind arm, never copied from a
        # feedback run. Result checks live only in observations below.
        if row.get("proposal") is not None:
            plan["proposal"] = deepcopy(row["proposal"])
        plans.append(plan)
    observations = [
        {key: deepcopy(row[key]) for key in OBSERVATION_FIELDS if key in row}
        for row in history
    ] if feedback_visible else []
    return {
        "schema_version": 1,
        "feedback_visible": feedback_visible,
        "profile": {key: deepcopy(profile[key]) for key in PROFILE_FIELDS if key in profile},
        "trial_budget": {"maximum": limit, "attempted": len(history), "remaining": limit - len(history)},
        "plans": plans,
        "observations": observations,
        "available_candidates": deepcopy(available),
        "selection_objective": "maximize inner search_score ("+profile.get("primary_metric","accuracy")+"); final holdout is unavailable",
    }


def _text(value, name, limit=800):
    if not isinstance(value, str) or not value.strip() or len(value) > limit:
        raise ValueError(f"{name} must be nonempty text of at most {limit} characters.")
    return value.strip()


def parse_proposal(answer, history, available, feedback_visible=True):
    required = {"candidate", "reason", "hypothesis", "review", "evidence_trials", "expected_change"}
    if not isinstance(answer, dict) or set(answer) != required:
        raise ValueError("Proposal must contain exactly the six documented fields.")
    candidate = answer["candidate"]
    if not isinstance(candidate, str) or candidate not in {item["id"] for item in available}:
        raise ValueError("Proposal must select an untried available candidate.")
    prior_ids = {row["trial"] for row in history}
    evidence = answer["evidence_trials"]
    if (not isinstance(evidence, list) or any(type(value) is not int for value in evidence)
        or len(set(evidence)) != len(evidence) or not set(evidence) <= prior_ids):
        raise ValueError("Evidence must reference distinct prior trial IDs.")
    if not feedback_visible and evidence:
        raise ValueError("The no-feedback arm cannot cite observed trial results.")
    expectation = answer["expected_change"]
    if expectation is not None:
        expected_fields = {"metric", "reference_trial", "direction", "min_delta"}
        if not isinstance(expectation, dict) or set(expectation) != expected_fields:
            raise ValueError("Invalid expected_change schema.")
        if expectation["metric"] not in METRICS or expectation["direction"] not in ("increase", "decrease"):
            raise ValueError("Unsupported expected metric or direction.")
        reference = expectation["reference_trial"]
        if type(reference) is not int or reference not in prior_ids:
            raise ValueError("Expectation must reference a prior trial, never the current or a future trial.")
        delta = expectation["min_delta"]
        if type(delta) not in (int, float) or not math.isfinite(delta) or delta < 0:
            raise ValueError("min_delta must be finite and nonnegative.")
        expectation = {**expectation, "min_delta": float(delta)}
    return Proposal(
        candidate, _text(answer["reason"], "reason"),
        _text(answer["hypothesis"], "hypothesis", 500),
        _text(answer["review"], "review", 500), list(evidence), expectation,
    )


def _number(value):
    return type(value) in (int, float) and math.isfinite(value)


def check_expectation(proposal, result, history):
    """Check a prediction against measurements, not the model's self-assessment.

    supported means this measurement met the predeclared numerical expectation;
    it is not evidence that a verbal causal explanation has been established.
    """
    expectation = (proposal or {}).get("expected_change")
    if expectation is None:
        return {"status": "not_stated"}
    reference = next((row for row in history if row["trial"] == expectation["reference_trial"]), None)
    metric = expectation["metric"]
    if (reference is None or reference.get("status") != "completed" or result.get("status") != "completed"
        or not _number(reference.get(metric)) or not _number(result.get(metric))):
        return {"status": "not_evaluable", "metric": metric, "reference_trial": expectation["reference_trial"]}
    delta = float(result[metric]) - float(reference[metric])
    directional_delta = delta if expectation["direction"] == "increase" else -delta
    return {
        "status": "supported" if directional_delta + 1e-12 >= expectation["min_delta"] else "not_supported",
        "metric": metric, "reference_trial": reference["trial"],
        "reference_value": float(reference[metric]), "observed_value": float(result[metric]),
        "observed_delta": delta, "direction": expectation["direction"],
        "required_delta": expectation["min_delta"],
    }


INSTRUCTION = """Choose one next classification experiment from available_candidates.
Return one JSON object with exactly these six fields:
candidate: an available ID;
reason: a brief practical decision basis;
hypothesis: one concise, testable expectation about this configuration;
review: a brief interpretation of earlier outcomes and expectation checks;
evidence_trials: prior trial IDs supporting the choice;
expected_change: null, or {metric, reference_trial, direction, min_delta}.
metric is search_score, score_gap, search_accuracy, generalization_gap, or training_seconds.
search_score is the declared primary metric; search_accuracy is a separate diagnostic.
direction is increase or decrease; min_delta is a nonnegative numerical change
relative to a prior trial. Accuracy is a fraction; time is measured in seconds.
If there is no usable reference, expected_change may be null. If results are
hidden, evidence_trials must be empty and review must acknowledge that outcomes
are unavailable; a relative prediction may still be declared without knowing
the reference score. Previous plans in that arm belong to its own blind run.
When observations are visible, examine the previous expectation check before
choosing the next configuration. A train/search gap suggests a hypothesis;
it does not prove overfitting or identify a cause. Consider failed trials too.
Choose a configuration whose result will inform the next decision. Do not
request test data, final holdout scores, arbitrary code, or extra experiments.
Give concise experiment notes, not a long reasoning transcript. Controller
limits and automatic final selection remain authoritative."""


class HypothesisAgent:
    """One metered LLM call per decision, with the existing choose() interface."""
    def __init__(self, client, logger, limit, feedback_visible=True):
        self.client, self.logger, self.limit = client, logger, limit
        self.feedback_visible = feedback_visible
        self.last_proposal = None

    def choose(self, profile, history, available):
        self.last_proposal = None
        state = build_state(profile, history, available, self.limit, self.feedback_visible)
        answer = self.client.ask({"instruction": INSTRUCTION, **state}, self.logger, "hypothesis_planner")
        proposal = parse_proposal(answer, history, available, self.feedback_visible)
        self.last_proposal = proposal.record()
        return proposal.candidate, proposal.reason
